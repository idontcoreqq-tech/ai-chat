/** Эвристика для мок-ответов, когда Gemini недоступен. */
export function isMedicalProductTopic(text) {
  const lower = text.toLowerCase().trim();
  const keywords = [
    'лекар',
    'препарат',
    'медицин',
    'аптек',
    'витамин',
    'бад',
    'таблет',
    'капсул',
    'сироп',
    'мазь',
    'крем',
    'спрей',
    'капли',
    'ингал',
    'рецепт',
    'дозир',
    'показан',
    'противопоказ',
    'состав',
    'аналог',
    'генерик',
    'наличи',
    'в наличии',
    'хранен',
    'срок год',
    'отпуск',
    'без рецепт',
    'антисепт',
    'обезбол',
    'противовирус',
    'пробиот',
    'термометр',
    'тонометр',
    'бинт',
    'пластыр',
    'маска мед',
    'перчатк',
    'шприц',
    'каталог',
    'артикул',
    'sku',
  ];
  const orderContext =
    /(заказ|доставк|оплат|возврат|купить|цена|стоимость|скид)/.test(lower) &&
    /(лекар|препарат|аптек|товар|мед)/.test(lower);
  return keywords.some((kw) => lower.includes(kw)) || orderContext;
}

